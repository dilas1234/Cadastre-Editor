//! Job-report and site-plan PDF builders (FR-OUT-*). Pure: they take plain data and return PDF
//! bytes, so they are unit-tested without a database.

use crate::pdf::{Page, A4_H, A4_W};

/// One row in a job report.
pub struct ParcelLine {
    /// Official parcel number, or `None` if unposted.
    pub number: Option<String>,
    /// Computed area (m²), if known.
    pub area_m2: Option<f64>,
    /// Parcel status.
    pub status: String,
}

/// Data for a job report.
pub struct JobReportData {
    /// Job reference.
    pub reference: String,
    /// Job status.
    pub status: String,
    /// Parcels in the job.
    pub parcels: Vec<ParcelLine>,
}

/// Render a one-page job report PDF.
pub fn job_report_pdf(d: &JobReportData) -> Vec<u8> {
    let mut p = Page::default();
    let mut y = A4_H - 60.0;
    p.text(72.0, y, 18.0, "PLAGIS Cadastre - Job Report");
    y -= 28.0;
    p.text(72.0, y, 11.0, &format!("Job reference: {}", d.reference));
    y -= 16.0;
    p.text(72.0, y, 11.0, &format!("Job status:    {}", d.status));
    y -= 16.0;
    p.text(72.0, y, 11.0, &format!("Parcels:       {}", d.parcels.len()));
    y -= 26.0;
    p.text(72.0, y, 11.0, "Parcel number       Area (m2)      Status");
    y -= 15.0;
    for line in &d.parcels {
        if y < 56.0 {
            p.text(72.0, y, 9.0, "… (truncated)");
            break;
        }
        let num = line.number.clone().unwrap_or_else(|| "(unposted)".to_string());
        let area = line.area_m2.map(|a| format!("{a:.1}")).unwrap_or_else(|| "-".to_string());
        p.text(72.0, y, 10.0, &format!("{num:<20}{area:<15}{}", line.status));
        y -= 13.0;
    }
    p.text(72.0, 40.0, 8.0, "Generated by cadastre-server.");
    p.into_pdf()
}

/// Render a site-plan PDF: the parcel rings scaled to fit the page, with a title.
pub fn site_plan_pdf(title: &str, rings: &[Vec<(f64, f64)>]) -> Vec<u8> {
    let mut p = Page::default();
    p.text(72.0, A4_H - 50.0, 16.0, title);

    // Bounding box of all vertices.
    let (mut minx, mut miny, mut maxx, mut maxy) =
        (f64::INFINITY, f64::INFINITY, f64::NEG_INFINITY, f64::NEG_INFINITY);
    for (x, y) in rings.iter().flatten() {
        minx = minx.min(*x);
        miny = miny.min(*y);
        maxx = maxx.max(*x);
        maxy = maxy.max(*y);
    }

    // Draw area inside margins.
    let (mx, my) = (72.0, 80.0);
    let (bw, bh) = (A4_W - 2.0 * mx, A4_H - my - 110.0);
    let (dx, dy) = (maxx - minx, maxy - miny);
    if dx.is_finite() && dy.is_finite() && (dx > 0.0 || dy > 0.0) {
        let scale = (bw / dx.max(1e-9)).min(bh / dy.max(1e-9));
        let to_page = |(x, y): &(f64, f64)| (mx + (x - minx) * scale, my + (y - miny) * scale);
        for ring in rings {
            let pts: Vec<(f64, f64)> = ring.iter().map(to_page).collect();
            p.polyline(&pts, true);
        }
        p.text(72.0, 52.0, 8.0, &format!("Extent (m): {minx:.1},{miny:.1} .. {maxx:.1},{maxy:.1}"));
    } else {
        p.text(72.0, A4_H - 90.0, 11.0, "No geometry to plot.");
    }
    p.into_pdf()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn job_report_is_valid_pdf_with_parcel_numbers() {
        let d = JobReportData {
            reference: "JOB-7".to_string(),
            status: "approved".to_string(),
            parcels: vec![
                ParcelLine { number: Some("PL000000000001".into()), area_m2: Some(1234.5), status: "posted".into() },
                ParcelLine { number: None, area_m2: None, status: "draft".into() },
            ],
        };
        let pdf = job_report_pdf(&d);
        assert!(pdf.starts_with(b"%PDF-1.4") && pdf.ends_with(b"%%EOF"));
        let s = String::from_utf8_lossy(&pdf);
        assert!(s.contains("PL000000000001"));
        assert!(s.contains("JOB-7"));
        // Parentheses are escaped in PDF strings, so match the inner text.
        assert!(s.contains("unposted"));
    }

    #[test]
    fn site_plan_scales_a_square_without_panicking() {
        let ring = vec![(1000.0, 1000.0), (1100.0, 1000.0), (1100.0, 1100.0), (1000.0, 1100.0)];
        let pdf = site_plan_pdf("Site Plan - JOB-7", &[ring]);
        assert!(pdf.starts_with(b"%PDF-1.4") && pdf.ends_with(b"%%EOF"));
        assert!(String::from_utf8_lossy(&pdf).contains("Site Plan - JOB-7"));
    }

    #[test]
    fn site_plan_handles_empty_geometry() {
        let pdf = site_plan_pdf("Empty", &[]);
        assert!(pdf.starts_with(b"%PDF-1.4"));
        assert!(String::from_utf8_lossy(&pdf).contains("No geometry to plot."));
    }
}
